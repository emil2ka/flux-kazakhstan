const assert = require('node:assert/strict');
const F = require('../proof-core.js');
const memory = () => { const map=new Map();return {getItem:k=>map.get(k),setItem:(k,v)=>map.set(k,v)}; };
const s=memory();
assert(F.check(F.read(s).draft).includes('transfer_conflict'));
assert.throws(()=>F.publish(s),/inconsistent/);
assert.equal(F.published(s).departure.price,55000);
F.saveDraft(F.DEFAULT,s);
const v=F.publish(s);
assert.equal(v.number,2);
const input={versionId:v.id,guests:2,guideLanguage:'de',name:'Demo Guest',email:'demo@example.test',accepted:true};
